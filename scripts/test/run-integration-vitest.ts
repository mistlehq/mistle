function readStringProperty(input: object, key: string): string | undefined {
  const value = Reflect.get(input, key);
  return typeof value === "string" ? value : undefined;
}

function readNumberProperty(input: object, key: string): number | undefined {
  const value = Reflect.get(input, key);
  return typeof value === "number" && Number.isFinite(value) ? value : undefined;
}

function readStringArrayProperty(input: object, key: string): string[] | undefined {
  const value = Reflect.get(input, key);
  return Array.isArray(value) && value.every((item) => typeof item === "string")
    ? value
    : undefined;
}

function parseIntegrationTimingFileRecord(input: unknown): IntegrationTimingFileRecord | undefined {
  if (typeof input !== "object" || input === null) {
    return undefined;
  }

  const type = readStringProperty(input, "type");
  const status = readStringProperty(input, "status");
  const label = readStringProperty(input, "label");
  const file = readStringProperty(input, "file");
  const services = readStringProperty(input, "services");
  const envId = readStringProperty(input, "envId");
  const setupMs = readNumberProperty(input, "setupMs");
  const bodyMs = readNumberProperty(input, "bodyMs");
  const teardownMs = readNumberProperty(input, "teardownMs");
  const totalMs = readNumberProperty(input, "totalMs");

  if (
    type !== "integration-file" ||
    (status !== "passed" && status !== "failed") ||
    label === undefined ||
    file === undefined ||
    services === undefined ||
    envId === undefined ||
    setupMs === undefined ||
    bodyMs === undefined ||
    teardownMs === undefined ||
    totalMs === undefined
  ) {
    return undefined;
  }

  return {
    type,
    label,
    file,
    services,
    envId,
    setupMs,
    bodyMs,
    teardownMs,
    totalMs,
    status,
  };
}

function parseVitestJsonAssertionResult(input: unknown): VitestJsonAssertionResult | undefined {
  if (typeof input !== "object" || input === null) {
    return undefined;
  }

  const title = readStringProperty(input, "title");
  const fullName = readStringProperty(input, "fullName");
  const ancestorTitles = readStringArrayProperty(input, "ancestorTitles");
  const status = readStringProperty(input, "status");
  const durationMs = readNumberProperty(input, "duration");

  if (
    title === undefined &&
    fullName === undefined &&
    ancestorTitles === undefined &&
    status === undefined &&
    durationMs === undefined
  ) {
    return undefined;
  }

  const result: VitestJsonAssertionResult = {};
  if (title !== undefined) {
    result.title = title;
  }
  if (fullName !== undefined) {
    result.fullName = fullName;
  }
  if (ancestorTitles !== undefined) {
    result.ancestorTitles = ancestorTitles;
  }
  if (status !== undefined) {
    result.status = status;
  }
  if (durationMs !== undefined) {
    result.durationMs = durationMs;
  }

  return result;
}

function parseVitestJsonResult(input: unknown): VitestJsonResult | undefined {
  if (typeof input !== "object" || input === null) {
    return undefined;
  }

  const assertionResults = Reflect.get(input, "assertionResults");
  const result: VitestJsonResult = {};
  const name = readStringProperty(input, "name");
  const status = readStringProperty(input, "status");
  const startTime = readNumberProperty(input, "startTime");
  const endTime = readNumberProperty(input, "endTime");

  if (name !== undefined) {
    result.name = name;
  }
  if (status !== undefined) {
    result.status = status;
  }
  if (startTime !== undefined) {
    result.startTime = startTime;
  }
  if (endTime !== undefined) {
    result.endTime = endTime;
  }
  if (Array.isArray(assertionResults)) {
    result.assertionResults = assertionResults
      .map((assertionResult) => parseVitestJsonAssertionResult(assertionResult))
      .filter((assertionResult) => assertionResult !== undefined);
  }

  return result;
}

function parseVitestJsonReport(input: unknown): VitestJsonReport {
  if (typeof input !== "object" || input === null) {
    return {};
  }

  const testResults = Reflect.get(input, "testResults");
  if (!Array.isArray(testResults)) {
    return {};
  }

  return {
    testResults: testResults
      .map((result) => parseVitestJsonResult(result))
      .filter((result) => result !== undefined),
  };
}

async function readIntegrationTimingRecords(
  eventsFile: string | undefined,
): Promise<IntegrationTimingFileRecord[]> {
  if (eventsFile === undefined) {
    return [];
  }

  let contents;
  try {
    contents = await readFile(eventsFile, "utf8");
  } catch (error) {
    if (isErrnoException(error) && error.code === "ENOENT") {
      return [];
    }
    throw error;
  }

  return contents
    .split("\n")
    .filter((line) => line.length > 0)
    .map((line) => parseIntegrationTimingFileRecord(JSON.parse(line)))
    .filter((record) => record !== undefined);
}

async function readVitestJsonResults(
  vitestJsonFile: string | undefined,
): Promise<Map<string, VitestJsonResult>> {
  const results = new Map<string, VitestJsonResult>();
  if (vitestJsonFile === undefined) {
    return results;
  }

  let contents;
  try {
    contents = await readFile(vitestJsonFile, "utf8");
  } catch (error) {
    if (isErrnoException(error) && error.code === "ENOENT") {
      return results;
    }
    throw error;
  }

  const report = parseVitestJsonReport(JSON.parse(contents));
  for (const result of report.testResults ?? []) {
    if (result.name === undefined) {
      continue;
    }
    results.set(normalizeReportFile(result.name), result);
  }

  return results;
}

function normalizeReportFile(file: string): string {
  const absolutePath = isAbsolute(file) ? file : resolve(process.cwd(), file);
  const relativePath = absolutePath.startsWith(`${process.cwd()}/`)
    ? absolutePath.slice(process.cwd().length + 1)
    : absolutePath;

  return relativePath.replaceAll("\\", "/");
}

function summarizeIntegrationTiming(input: {
  records: ReadonlyArray<IntegrationTimingFileRecord>;
  vitestResults: ReadonlyMap<string, VitestJsonResult>;
}): IntegrationTimingSummaryRow[] {
  const rows = new Map<string, IntegrationTimingSummaryRow>();

  for (const record of input.records) {
    const file = normalizeReportFile(record.file);
    const existing = rows.get(file);
    if (existing === undefined) {
      rows.set(file, {
        file,
        services: record.services,
        setupMs: record.setupMs,
        bodyMs: record.bodyMs,
        teardownMs: record.teardownMs,
        totalMs: record.totalMs,
        tests: undefined,
        status: record.status,
      });
      continue;
    }

    existing.setupMs += record.setupMs;
    existing.bodyMs += record.bodyMs;
    existing.teardownMs += record.teardownMs;
    existing.totalMs += record.totalMs;
    existing.status =
      existing.status === "failed" || record.status === "failed" ? "failed" : "passed";
    if (!existing.services.split(" | ").includes(record.services)) {
      existing.services = `${existing.services} | ${record.services}`;
    }
  }

  for (const [file, row] of rows.entries()) {
    const vitestResult = input.vitestResults.get(file);
    if (vitestResult === undefined) {
      continue;
    }
    row.tests = vitestResult.assertionResults?.length;
    row.status = vitestResult.status ?? row.status;
    if (vitestResult.startTime !== undefined && vitestResult.endTime !== undefined) {
      const vitestDurationMs = vitestResult.endTime - vitestResult.startTime;
      if (vitestDurationMs > 0) {
        row.totalMs = vitestDurationMs;
      }
    }
  }

  return [...rows.values()];
}

function summarizeIntegrationTestCaseTiming(input: {
  vitestResults: ReadonlyMap<string, VitestJsonResult>;
}): IntegrationTimingTestCaseRow[] {
  const rows: IntegrationTimingTestCaseRow[] = [];

  for (const [file, result] of input.vitestResults.entries()) {
    for (const assertionResult of result.assertionResults ?? []) {
      if (assertionResult.durationMs === undefined) {
        continue;
      }

      const testName =
        assertionResult.fullName ??
        [...(assertionResult.ancestorTitles ?? []), assertionResult.title ?? "(unnamed test)"].join(
          " > ",
        );
      rows.push({
        file,
        testName,
        durationMs: assertionResult.durationMs,
        status: assertionResult.status ?? result.status ?? "unknown",
      });
    }
  }

  return rows;
}

function truncateMiddle(value: string, width: number): string {
  if (value.length <= width) {
    return value.padEnd(width);
  }
  if (width <= 1) {
    return value.slice(0, width);
  }

  return `${value.slice(0, width - 1)}…`;
}

function formatReportCount(count: number | undefined): string {
  return count === undefined ? "-" : String(count);
}

function writeTimingTable(input: {
  title: string;
  rows: ReadonlyArray<IntegrationTimingSummaryRow>;
  sortBy: keyof Pick<IntegrationTimingSummaryRow, "totalMs" | "bodyMs" | "setupMs" | "teardownMs">;
}): void {
  const rows = [...input.rows].sort((left, right) => right[input.sortBy] - left[input.sortBy]);
  if (rows.length === 0) {
    return;
  }

  console.info(`\n[integration] ${input.title}`);
  console.info(
    [
      "file".padEnd(72),
      "total".padStart(7),
      "setup".padStart(7),
      "body".padStart(7),
      "teardown".padStart(9),
      "tests".padStart(5),
      "status".padEnd(7),
      "services",
    ].join("  "),
  );
  for (const row of rows.slice(0, 15)) {
    console.info(
      [
        truncateMiddle(row.file, 72),
        formatDuration(row.totalMs).padStart(7),
        formatDuration(row.setupMs).padStart(7),
        formatDuration(row.bodyMs).padStart(7),
        formatDuration(row.teardownMs).padStart(9),
        formatReportCount(row.tests).padStart(5),
        row.status.padEnd(7),
        row.services,
      ].join("  "),
    );
  }
}

function writeTestCaseTimingTable(rows: ReadonlyArray<IntegrationTimingTestCaseRow>): void {
  const sortedRows = [...rows].sort((left, right) => right.durationMs - left.durationMs);
  if (sortedRows.length === 0) {
    return;
  }

  console.info("\n[integration] slowest integration test cases by wall time");
  console.info(["file".padEnd(58), "duration".padStart(8), "status".padEnd(7), "test"].join("  "));
  for (const row of sortedRows.slice(0, 15)) {
    console.info(
      [
        truncateMiddle(row.file, 58),
        formatDuration(row.durationMs).padStart(8),
        row.status.padEnd(7),
        truncateMiddle(row.testName, 100),
      ].join("  "),
    );
  }
}

async function writeIntegrationTimingSummary(input: {
  eventsFile: string | undefined;
  vitestJsonFile: string | undefined;
}): Promise<void> {
  const records = await readIntegrationTimingRecords(input.eventsFile);
  if (records.length === 0) {
    return;
  }

  const vitestResults = await readVitestJsonResults(input.vitestJsonFile);
  const rows = summarizeIntegrationTiming({
    records,
    vitestResults,
  });

  writeTimingTable({
    title: "slowest integration files by wall time",
    rows,
    sortBy: "totalMs",
  });
  writeTestCaseTimingTable(
    summarizeIntegrationTestCaseTiming({
      vitestResults,
    }),
  );
  writeTimingTable({
    title: "largest aggregate integration body targets",
    rows,
    sortBy: "bodyMs",
  });
}

async function readExtraInfraPrewarmPlanFromTests(input: {
  selectedProjects: ReadonlyArray<IntegrationVitestProject>;
  fileFilters: ReadonlyArray<string>;
}): Promise<Pick<SharedInfraPrewarmPlan, "mailpit" | "seaweedfs">> {
  const files =
    input.fileFilters.length === 0
      ? (
          await Promise.all(
            input.selectedProjects.map((project) =>
              listIntegrationTestFiles(resolve(process.cwd(), project.packageDir, "integration")),
            ),
          )
        ).flat()
      : input.fileFilters.map((fileFilter) =>
          isAbsolute(fileFilter) ? fileFilter : resolve(process.cwd(), fileFilter),
        );

  const plan = {
    mailpit: false,
    seaweedfs: false,
  };

  await Promise.all(
    files.map(async (file) => {
      let contents;
      try {
        contents = await readFile(file, "utf8");
      } catch (error) {
        if (isErrnoException(error) && error.code === "ENOENT") {
          return;
        }
        throw error;
      }

      if (/extraInfra\s*:\s*\[[^\]]*["']mailpit["']/s.test(contents)) {
        plan.mailpit = true;
      }
      if (/extraInfra\s*:\s*\[[^\]]*["']seaweedfs["']/s.test(contents)) {
        plan.seaweedfs = true;
      }
    }),
  );

  return plan;
}

async function resolveSharedInfraPrewarmPlan(
  selectedProjects: ReadonlyArray<IntegrationVitestProject>,
  fileFilters: ReadonlyArray<string>,
): Promise<SharedInfraPrewarmPlan> {
  const plan: SharedInfraPrewarmPlan = {
    postgres: false,
    mailpit: false,
    seaweedfs: false,
    valkey: false,
  };

  for (const project of selectedProjects) {
    switch (project.appServicePrewarm) {
      case "control-plane":
      case "data-plane":
      case "worker":
        plan.postgres = true;
        break;
      case "gateway":
        plan.postgres = true;
        plan.valkey = true;
        break;
      case "none":
        break;
    }
  }

  const extraInfraPlan = await readExtraInfraPrewarmPlanFromTests({
    selectedProjects,
    fileFilters,
  });
  plan.mailpit = extraInfraPlan.mailpit;
  plan.seaweedfs = extraInfraPlan.seaweedfs;

  return plan;
}

function describeSharedInfraPrewarmPlan(plan: SharedInfraPrewarmPlan): string {
  const services: string[] = [];
  if (plan.postgres) {
    services.push("postgres");
  }
  if (plan.mailpit) {
    services.push("mailpit");
  }
  if (plan.seaweedfs) {
    services.push("seaweedfs");
  }
  if (plan.valkey) {
    services.push("valkey");
  }

  return services.length === 0 ? "none" : services.join(", ");
}

async function prewarmSharedInfra(
  selectedProjects: ReadonlyArray<IntegrationVitestProject>,
  fileFilters: ReadonlyArray<string>,
  coordinator: SharedInfraCoordinator,
): Promise<void> {
  const plan = await resolveSharedInfraPrewarmPlan(selectedProjects, fileFilters);
  if (!plan.postgres && !plan.mailpit && !plan.seaweedfs && !plan.valkey) {
    writeIntegrationTimingEvent("runner shared infra prewarm skipped", "none required");
    return;
  }

  const startedAt = Date.now();
  console.info(`[integration] prewarming shared infra: ${describeSharedInfraPrewarmPlan(plan)}.`);
  await coordinator.acquireSharedInfraCoordinatorLease({
    key: coordinator.createTestEnvironmentSharedInfraKey(process.env),
    postgres: plan.postgres ? {} : undefined,
    mailpit: plan.mailpit,
    seaweedfs: plan.seaweedfs,
    valkey: plan.valkey,
  });
  console.info(
    `[integration] shared infra prewarm completed in ${formatDuration(Date.now() - startedAt)}.`,
  );
}

function markIntegrationTimingStart(environment: NodeJS.ProcessEnv): void {
  if (environment["MISTLE_TEST_TIMING"] !== TimingEnabledValue) {
    return;
  }

  if (environment[TimingStartedAtEnv] === undefined) {
    environment[TimingStartedAtEnv] = String(Date.now());
  }
}

function writeIntegrationTimingEvent(event: string, details: string): void {
  if (process.env["MISTLE_TEST_TIMING"] !== TimingEnabledValue) {
    return;
  }

  process.stderr.write(
    `[integration] ${formatTimingOffset()} pid=${String(process.pid)} worker=unknown ${event}: ${details}.\n`,
  );
}

async function ensureIntegrationConfigPath(input: {
  runnerPoolSession: { coordinatorDir: string };
  environment: NodeJS.ProcessEnv;
}): Promise<void> {
  const existingConfigPath = input.environment["MISTLE_CONFIG_PATH"];
  if (existingConfigPath !== undefined && existingConfigPath.length > 0) {
    console.info(`[integration] using config from MISTLE_CONFIG_PATH: ${existingConfigPath}.`);
    return;
  }

  const configPath = join(input.runnerPoolSession.coordinatorDir, "config", "config.toml");
  await mkdir(dirname(configPath), { recursive: true });
  await writeFile(
    configPath,
    stringifyTomlConfig({
      header: IntegrationConfigHeader,
      configRoot: buildDevelopmentTomlConfig(),
    }),
    "utf8",
  );
  input.environment["MISTLE_CONFIG_PATH"] = configPath;
  console.info(`[integration] generated runner config: ${configPath}.`);
}

function formatTimingOffset(): string {
  const startedAtValue = process.env[TimingStartedAtEnv];
  if (startedAtValue === undefined || startedAtValue.length === 0) {
    return "t=unknown";
  }

  const startedAt = Number(startedAtValue);
  if (!Number.isFinite(startedAt)) {
    return "t=unknown";
  }

  return `t=+${formatDuration(Date.now() - startedAt)}`;
}

async function runCommand(command: string, args: ReadonlyArray<string>): Promise<void> {
  await new Promise<void>((resolvePromise, reject) => {
    writeIntegrationTimingEvent("runner command spawn", `${command} ${args.join(" ")}`);
    const child = spawn(command, args, {
      cwd: process.cwd(),
      env: process.env,
      stdio: "inherit",
    });

    writeIntegrationTimingEvent(
      "runner command spawned",
      `${command} pid=${child.pid === undefined ? "unknown" : String(child.pid)}`,
    );

    child.on("error", reject);
    child.on("exit", (code, signal) => {
      writeIntegrationTimingEvent(
        "runner command exited",
        `${command} code=${String(code)} signal=${signal === null ? "none" : signal}`,
      );
      if (code === 0) {
        resolvePromise();
        return;
      }

      reject(
        new Error(
          `${command} ${args.join(" ")} exited with code ${String(code)}${signal === null ? "" : ` and signal ${signal}`}.`,
        ),
      );
    });
  });
}

async function runTimedCommand(input: {
  label: string;
  command: string;
  args: ReadonlyArray<string>;
}): Promise<void> {
  const startedAt = Date.now();
  await runCommand(input.command, input.args);
  console.info(
    `[integration] ${input.label} completed in ${formatDuration(Date.now() - startedAt)}.`,
  );
}

