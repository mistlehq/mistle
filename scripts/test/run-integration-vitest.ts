function normalizeCliArgs(rawArgs: ReadonlyArray<string>): string[] {
  if (rawArgs[0] === "--") {
    return rawArgs.slice(1);
  }

  return [...rawArgs];
}

function parseProjectFilters(args: ReadonlyArray<string>): string[] {
  const projectFilters: string[] = [];

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === undefined) {
      throw new Error(`Expected an argument at index ${String(index)}.`);
    }
    if (argument === "--project") {
      const projectName = args[index + 1];
      if (projectName === undefined || projectName.length === 0) {
        throw new Error("Expected a project name after --project.");
      }
      projectFilters.push(projectName);
      index += 1;
      continue;
    }

    const projectPrefix = "--project=";
    if (argument.startsWith(projectPrefix)) {
      const projectName = argument.slice(projectPrefix.length);
      if (projectName.length === 0) {
        throw new Error("Expected a non-empty project name in --project=<name>.");
      }
      projectFilters.push(projectName);
    }
  }

  return projectFilters;
}

function parseIntegrationFileFilters(args: ReadonlyArray<string>): string[] {
  const fileFilters: string[] = [];

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === undefined) {
      throw new Error(`Expected an argument at index ${String(index)}.`);
    }
    if (argument === "--project") {
      index += 1;
      continue;
    }
    if (argument.startsWith("--")) {
      continue;
    }
    if (argument.includes("integration/") || argument.endsWith(".ts")) {
      fileFilters.push(argument);
    }
  }

  return fileFilters;
}

function resolveSelectedProjects(
  projectFilters: ReadonlyArray<string>,
): IntegrationVitestProject[] {
  if (projectFilters.length === 0) {
    return [...IntegrationVitestProjects];
  }

  const selectedProjects: IntegrationVitestProject[] = [];

  for (const projectFilter of projectFilters) {
    const project = IntegrationVitestProjects.find(
      (candidate) => candidate.projectName === projectFilter,
    );
    if (project === undefined) {
      throw new Error(
        `Unknown integration Vitest project '${projectFilter}'. Expected one of: ${IntegrationVitestProjects.map((candidate) => candidate.projectName).join(", ")}.`,
      );
    }
    if (!selectedProjects.includes(project)) {
      selectedProjects.push(project);
    }
  }

  return selectedProjects;
}

function formatDuration(milliseconds: number): string {
  return `${(milliseconds / 1000).toFixed(2)}s`;
}

async function listIntegrationTestFiles(directory: string): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (isErrnoException(error) && error.code === "ENOENT") {
      return [];
    }
    throw error;
  }

  const files: string[] = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listIntegrationTestFiles(path)));
      continue;
    }
    if (entry.isFile() && entry.name.endsWith(".test.ts")) {
      files.push(path);
    }
  }

  return files;
}

function isErrnoException(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}

function isTimingEnabled(environment: NodeJS.ProcessEnv): boolean {
  return environment["MISTLE_TEST_TIMING"] === TimingEnabledValue;
}

function hasCliOption(args: ReadonlyArray<string>, option: string): boolean {
  const optionPrefix = `${option}=`;
  const dottedOptionPrefix = `${option}.`;
  return args.some(
    (argument) =>
      argument === option ||
      argument.startsWith(optionPrefix) ||
      argument.startsWith(dottedOptionPrefix),
  );
}

function createTimingArtifacts(input: {
  runnerPoolSession: { coordinatorDir: string };
  environment: NodeJS.ProcessEnv;
}): { eventsFile: string; vitestJsonFile: string } | undefined {
  if (!isTimingEnabled(input.environment)) {
    return undefined;
  }

  const timingDir = join(input.runnerPoolSession.coordinatorDir, "timing");
  const artifacts = {
    eventsFile:
      input.environment[TimingEventsFileEnv] ?? join(timingDir, "integration-events.jsonl"),
    vitestJsonFile: join(timingDir, "vitest-results.json"),
  };
  input.environment[TimingEventsFileEnv] = artifacts.eventsFile;

  return artifacts;
}

async function initializeTimingArtifacts(
  artifacts: { eventsFile: string; vitestJsonFile: string } | undefined,
): Promise<void> {
  if (artifacts === undefined) {
    return;
  }

  await mkdir(dirname(artifacts.eventsFile), { recursive: true });
  await writeFile(artifacts.eventsFile, "", "utf8");
  await mkdir(dirname(artifacts.vitestJsonFile), { recursive: true });
}

