async function main(): Promise<void> {
  const startedAt = Date.now();
  markIntegrationTimingStart(process.env);
  const runnerPoolSession = ensureIntegrationRunnerPoolSession(process.env);
  const cliArgs = normalizeCliArgs(process.argv.slice(2));
  const projectFilters = parseProjectFilters(cliArgs);
  const fileFilters = parseIntegrationFileFilters(cliArgs);
  const selectedProjects = resolveSelectedProjects(projectFilters);
  const selectedBuildPackages = new Set<string>(RequiredBuildPackages);
  const timingArtifacts = createTimingArtifacts({
    runnerPoolSession,
    environment: process.env,
  });
  await initializeTimingArtifacts(timingArtifacts);
  const vitestCliArgs = addTimingVitestReporter({
    cliArgs,
    vitestJsonFile: timingArtifacts?.vitestJsonFile,
  });

  for (const project of selectedProjects) {
    selectedBuildPackages.add(project.packageName);
  }

  console.info(`Using integration run id ${runnerPoolSession.runId}.`);
  await ensureIntegrationConfigPath({
    runnerPoolSession,
    environment: process.env,
  });
  writeIntegrationTimingEvent(
    "runner selected projects",
    selectedProjects.map((project) => project.projectName).join(", "),
  );

  await runTimedCommand({
    label: "build",
    command: "pnpm",
    args: [
      "turbo",
      "run",
      "build",
      ...Array.from(selectedBuildPackages).flatMap((packageName) => [
        "--filter",
        `${packageName}...`,
      ]),
    ],
  });

  const sharedInfraCoordinator = await loadSharedInfraCoordinator();
  const runnerServicePools = await loadRunnerServicePools();

  try {
    await prewarmSharedInfra(selectedProjects, fileFilters, sharedInfraCoordinator);
    try {
      await runTimedCommand({
        label: "vitest",
        command: "pnpm",
        args: ["exec", "vitest", "run", "-c", "vitest.integration.root.ts", ...vitestCliArgs],
      });
    } finally {
      await writeIntegrationTimingSummary({
        eventsFile: timingArtifacts?.eventsFile,
        vitestJsonFile: timingArtifacts?.vitestJsonFile,
      });
    }
  } finally {
    const cleanupStartedAt = Date.now();
    await runnerServicePools.stopRunnerServicePools({
      runId: runnerPoolSession.runId,
      coordinatorDir: runnerPoolSession.coordinatorDir,
    });
    await sharedInfraCoordinator.stopSharedInfraForTestRun(runnerPoolSession.runId);
    console.info(
      `[integration] pooled service/infra cleanup completed in ${formatDuration(Date.now() - cleanupStartedAt)}.`,
    );
  }

  console.info(`[integration] total completed in ${formatDuration(Date.now() - startedAt)}.`);
}

main().catch((error: unknown) => {
  const message = error instanceof Error ? (error.stack ?? error.message) : String(error);
  console.error(message);
  process.exitCode = 1;
});
